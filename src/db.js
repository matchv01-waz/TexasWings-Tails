'use strict';
// Postgres database.
//   • DATABASE_URL set (e.g. Neon)  → node-postgres connection pool
//   • DATABASE_URL not set          → PGlite, an embedded Postgres stored in DATA_DIR/pglite
//     (local development and tests only — needs no setup)
// Both speak the same SQL. Queries are written with "?" placeholders, which are
// converted to Postgres "$1, $2…" automatically.

const path = require('path');
const fs = require('fs');

const DATA_DIR = path.resolve(process.env.DATA_DIR || path.join(__dirname, '..', 'data'));
