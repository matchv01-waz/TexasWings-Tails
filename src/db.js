// "?" → "$1, $2 …" (none of our SQL contains a literal question mark)
function toPg(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => '$' + ++i);
}

// get/all/run bound to a query function (the pool, or a transaction client)
function bind(exec) {
  const q = async (sql, params) => exec(toPg(sql), params.length ? params : undefined);
  return {
    get: async (sql, ...p) => (await q(sql, p)).rows[0],
    all: async (sql, ...p) => (await q(sql, p)).rows,
    run: async (sql, ...p) => q(sql, p),
  };
}

let driver = null;
let ready = null;

// Neon's connection strings say "sslmode=require". node-postgres already treats that as full
// certificate verification ("verify-full") but prints a long warning about it; ask for
// verify-full explicitly so the behavior stays the same and the logs stay clean.
function connectionString() {
  const raw = process.env.DATABASE_URL;
  try {
    const u = new URL(raw);
    if (['require', 'prefer', 'verify-ca'].includes(u.searchParams.get('sslmode'))) u.searchParams.set('sslmode', 'verify-full');
    return u.toString();
  } catch {
    return raw;
  }
}

async function connect() {
  if (USING_PG) {
    const { Pool } = require('pg');
    const pool = new Pool({
      connectionString: connectionString(),
      max: Number(process.env.PG_POOL_MAX) || 5,
      idleTimeoutMillis: 30000,
      connectionTimeoutMillis: 15000, // Neon may need a moment to wake up
    });
    pool.on('error', (e) => console.error('Database connection error:', e.message));
    return {
      kind: 'postgres',
      query: (sql, params) => pool.query(sql, params),
      exec: (sql) => pool.query(sql),
      async transaction(fn) {
        const client = await pool.connect();
        try {
          await client.query('BEGIN');
          const result = await fn((sql, params) => client.query(sql, params));
          await client.query('COMMIT');
          return result;
        } catch (e) {
          await client.query('ROLLBACK').catch(() => {});
          throw e;
        } finally {
          client.release();
        }
      },
      end: () => pool.end(),
    };
  }
  fs.mkdirSync(DATA_DIR, { recursive: true });
  const { PGlite } = await import('@electric-sql/pglite');
  const pg = await PGlite.create(path.join(DATA_DIR, 'pglite'));
  return {
    kind: 'pglite',
    query: (sql, params) => pg.query(sql, params),
    exec: (sql) => pg.exec(sql),
    transaction: (fn) => pg.transaction((t) => fn((sql, params) => t.query(sql, params))),
    end: () => pg.close(),
  };
}

const main = bind((sql, params) => driver.query(sql, params));

/** Connect, create tables and seed starter content. Safe to call more than once. */
function init() {
  if (!ready) {
    ready = (async () => {
      driver = await connect();
      await driver.exec(SCHEMA);
      await seed();
      return driver.kind;
    })();
  }
  return ready;
}

async function tx(fn) {
  return driver.transaction((exec) => fn(bind(exec)));
}

const marks = (n) => Array(n).fill('?').join(', ');

async function seed() {
  const content = require('./seed-content');
  if (!(await main.get('SELECT COUNT(*)::int AS n FROM species')).n) {
    await tx(async (q) => {
      for (const [i, s] of content.species.entries()) {
        await q.run(
          `INSERT INTO species (slug, name, singular, scientific_name, tagline, overview, personality, characteristics,
            care, size, lifespan, noise_level, diet, socialization, accent, sort_order)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          s.slug, s.name, s.singular, s.scientific_name, s.tagline, s.overview, s.personality, s.characteristics,
          s.care, s.size, s.lifespan, s.noise_level, s.diet, s.socialization, s.accent, i + 1);
      }
    });
  }
  if (!(await main.get('SELECT COUNT(*)::int AS n FROM faqs')).n) {
    await tx(async (q) => {
      for (const [i, f] of content.faqs.entries()) {
        await q.run('INSERT INTO faqs (question, answer, published, sort_order) VALUES (?, ?, ?, ?)',
          f.question, f.answer || '', f.answer ? 1 : 0, i + 1);
      }
    });
  }
}

async function close() {
  if (driver) await driver.end();
  driver = null;
  ready = null;
}

module.exports = { init, close, tx, marks, get: main.get, all: main.all, run: main.run, DATA_DIR, UPLOAD_DIR, USING_PG };
